/**
 * Demo data: two complete, independent jewellery stores.
 *
 * Deliberately two, with overlapping slugs and SKUs, because that is the
 * fixture the isolation suite needs: if `rings` or `SKU-001` means something
 * different in each store, any leak between them is immediately visible.
 *
 * The products are realistic rather than random — a 22K bangle priced by
 * weight and making charge exercises the pricing rules that matter, where
 * `faker.commerce.productName()` would not.
 *
 * Never runs when NODE_ENV=production (checked by the caller).
 */
