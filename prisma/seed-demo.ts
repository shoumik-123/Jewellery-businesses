const DEMO_PASSWORD = 'DemoStore!2026';

export async function seedDemoData(prisma: Prisma): Promise<void> {
  const themes = await prisma.theme.findMany();
  const plans = await prisma.subscriptionPlan.findMany();
  const ownerRole = await prisma.role.findUniqueOrThrow({ where: { key: 'store_owner' } });
  const passwordHash = await hashPassword(DEMO_PASSWORD);

  for (const [index, storeSeed] of STORES.entries()) {
    const products = index === 0 ? GOLD_PRODUCTS : SILVER_PRODUCTS;
    const theme = themes.find((t) => t.key === storeSeed.themeKey);
    const plan = plans.find((p) => p.key === storeSeed.planKey);
    if (!theme || !plan) throw new Error('Seed reference data first (themes and plans).');

    // --- owner, tenant, store -------------------------------------------
    const owner = await prisma.user.upsert({
      where: { email: storeSeed.ownerEmail },
      create: {
        email: storeSeed.ownerEmail,
        firstName: storeSeed.ownerFirstName,
        lastName: storeSeed.ownerLastName,
        phone: storeSeed.phone,
        passwordHash,
        status: 'ACTIVE',
        emailVerifiedAt: new Date(),
      },
      update: {},
    });

    const tenant = await prisma.tenant.upsert({
      where: { slug: storeSeed.slug },
      create: {
        slug: storeSeed.slug,
        name: storeSeed.name,
        ownerUserId: owner.id,
        status: 'ACTIVE',
        businessName: storeSeed.name,
        billingEmail: storeSeed.ownerEmail,
      },
      update: {},
    });

    const now = new Date();
    const periodEnd = new Date(now);
    periodEnd.setMonth(periodEnd.getMonth() + 1);
    const trialEnd = new Date(now);
    trialEnd.setDate(trialEnd.getDate() + plan.trialDays);

    const existingSubscription = await prisma.subscription.findFirst({
      where: { tenantId: tenant.id },
    });
    if (!existingSubscription) {
      await prisma.subscription.create({
        data: {
          tenantId: tenant.id,
          planId: plan.id,
          status: 'TRIALING',
          interval: 'MONTHLY',
          priceAmount: plan.monthlyPrice,
          currency: plan.currency,
          currentPeriodStart: now,
          currentPeriodEnd: periodEnd,
          trialEndsAt: trialEnd,
        },
      });
    }

    const store = await prisma.store.upsert({
      where: { slug: storeSeed.slug },
      create: {
        tenantId: tenant.id,
        slug: storeSeed.slug,
        name: storeSeed.name,
        tagline: storeSeed.tagline,
        status: 'ACTIVE',
        email: storeSeed.ownerEmail,
        phone: storeSeed.phone,
        city: storeSeed.city,
        logoUrl: `/demo/logo-${storeSeed.slug}.svg`,
        publishedAt: now,
      },
      update: {},
    });

    // The upsert above leaves an existing store alone, so a re-seed never
    // clobbers edits made through the dashboard. The logo is the one thing
    // worth backfilling, and only when the store has none.
    await prisma.store.updateMany({
      where: { id: store.id, logoUrl: null },
      data: { logoUrl: `/demo/logo-${storeSeed.slug}.svg` },
    });

    await prisma.storeMember.upsert({
      where: { storeId_userId: { storeId: store.id, userId: owner.id } },
      create: {
        storeId: store.id,
        userId: owner.id,
        roleId: ownerRole.id,
        isOwner: true,
        status: 'ACTIVE',
        acceptedAt: now,
      },
      update: {},
    });

    await prisma.storeSettings.upsert({
      where: { storeId: store.id },
      create: { storeId: store.id, lowStockThreshold: 2 },
      update: {},
    });

    await prisma.storeDomain.upsert({
      where: { hostname: `${storeSeed.slug}.jewelleryhub.test` },
      create: {
        storeId: store.id,
        hostname: `${storeSeed.slug}.jewelleryhub.test`,
        type: 'SUBDOMAIN',
        isPrimary: true,
        verifiedAt: now,
        sslStatus: 'ISSUED',
      },
      update: {},
    });

    const existingTheme = await prisma.storeTheme.findFirst({
      where: { storeId: store.id, themeId: theme.id },
    });
    if (!existingTheme) {
      await prisma.storeTheme.create({
        data: { storeId: store.id, themeId: theme.id, isActive: true, tokens: {} },
      });
    }

    // --- home page with sections ----------------------------------------
    const homePage = await prisma.storePage.upsert({
      where: { storeId_slug: { storeId: store.id, slug: 'home' } },
      create: {
        storeId: store.id,
        slug: 'home',
        type: 'HOME',
        title: storeSeed.name,
        status: 'PUBLISHED',
        publishedAt: now,
        seoTitle: `${storeSeed.name} — ${storeSeed.tagline}`,
      },
      update: {},
    });

    const sections: Array<{ type: string; settings: Record<string, unknown> }> = [
      {
        type: 'hero',
        settings: {
          heading: storeSeed.name,
          subheading: storeSeed.tagline,
          ctaLabel: 'Shop the collection',
          ctaHref: '/shop',
          alignment: 'center',
        },
      },
      { type: 'categoryStrip', settings: { title: 'Shop by category', limit: 6 } },
      {
        type: 'featuredProducts',
        settings: { title: 'Featured pieces', limit: 4, source: 'featured' },
      },
      {
        type: 'richText',
        settings: {
          heading: 'Why buy from us',
          body:
            index === 0
              ? 'Every gold piece is BSTI hallmarked and priced transparently: metal weight at the day’s rate, plus a stated making charge.'
              : 'Each piece is made by hand in small batches in our Chattogram studio, in solid 925 silver.',
        },
      },
      { type: 'newsletter', settings: { heading: 'New arrivals, first look' } },
    ];

    const existingSections = await prisma.storePageSection.count({
      where: { pageId: homePage.id },
    });
    if (existingSections === 0) {
      await prisma.storePageSection.createMany({
        data: sections.map((section, position) => ({
          pageId: homePage.id,
          storeId: store.id,
          type: section.type,
          position,
          settings: section.settings,
        })),
      });
    }

    // --- inventory location ---------------------------------------------
    const location = await prisma.inventoryLocation.upsert({
      where: { storeId_code: { storeId: store.id, code: 'MAIN' } },
      create: {
        storeId: store.id,
        code: 'MAIN',
        name: index === 0 ? 'Gulshan Showroom' : 'Studio',
        isDefault: true,
      },
      update: {},
    });

    // --- metal rates -----------------------------------------------------
    for (const rate of METAL_RATES) {
      const effectiveFrom = new Date(now.getFullYear(), now.getMonth(), now.getDate());
      await prisma.metalRate.upsert({
        where: {
          storeId_metalType_purity_effectiveFrom: {
            storeId: store.id,
            metalType: rate.metalType,
            purity: rate.purity,
            effectiveFrom,
          },
        },
        create: {
          storeId: store.id,
          metalType: rate.metalType,
          purity: rate.purity,
          ratePerGram: rate.ratePerGram,
          effectiveFrom,
          source: 'manual',
        },
        update: { ratePerGram: rate.ratePerGram },
      });
    }

    // --- categories ------------------------------------------------------
    const categoryNames = [...new Set(products.map((p) => p.category))];
    const categories = new Map<string, string>();
    for (const [position, name] of categoryNames.entries()) {
      const slug = slugify(name);
      const category = await prisma.category.upsert({
        where: { storeId_slug: { storeId: store.id, slug } },
        create: {
          storeId: store.id,
          slug,
          name,
          position,
          isActive: true,
          isFeatured: position < 4,
        },
        update: {},
      });
      categories.set(name, category.id);
    }

    // --- products --------------------------------------------------------
    let productCount = 0;
    for (const [position, seed] of products.entries()) {
      const slug = slugify(seed.name);
      const categoryId = categories.get(seed.category);

      const product = await prisma.product.upsert({
        where: { storeId_slug: { storeId: store.id, slug } },
        create: {
          storeId: store.id,
          primaryCategoryId: categoryId ?? null,
          name: seed.name,
          slug,
          sku: seed.sku,
          shortDescription: seed.shortDescription,
          description: `<p>${seed.shortDescription}</p>`,
          status: 'ACTIVE',
          availability: 'IN_STOCK',
          jewelleryType: seed.jewelleryType,
          metalType: seed.metalType,
          metalPurity: seed.purity,
          hallmarked: seed.hallmarked ?? false,
          grossWeightG: seed.grossWeightG,
          netWeightG: seed.netWeightG,
          stoneType: seed.stoneType ?? null,
          pricingMode: seed.rateBased === true ? 'METAL_RATE_BASED' : 'FIXED',
          costPrice: seed.costPrice,
          price: seed.price,
          salePrice: seed.salePrice ?? null,
          makingCharge: seed.makingCharge ?? null,
          makingChargeType: seed.makingChargeType ?? 'FLAT',
          wastagePercent: seed.wastagePercent ?? null,
          isFeatured: seed.featured ?? false,
          position,
          publishedAt: now,
          tags: [seed.metalType.toLowerCase(), seed.jewelleryType.toLowerCase()],
        },
        update: {},
      });
      productCount += 1;

      if (categoryId) {
        await prisma.productCategory.upsert({
          where: { productId_categoryId: { productId: product.id, categoryId } },
          create: { productId: product.id, categoryId },
          update: {},
        });
      }

      // --- catalogue imagery ---------------------------------------------
      // A product with no artwork is a seeding mistake, not something to let
      // through quietly: it would ship a storefront with holes in it.
      const artwork = ARTWORK.get(slug);
      if (!artwork) {
        throw new Error(
          `No demo artwork for "${slug}". Add it to PIECES in scripts/generate-demo-media.ts and run pnpm media:generate.`,
        );
      }

      const existingMedia = await prisma.productMedia.count({ where: { productId: product.id } });
      if (existingMedia === 0) {
        await prisma.productMedia.createMany({
          data: [
            {
              storeId: store.id,
              productId: product.id,
              type: 'IMAGE',
              url: `/demo/${artwork.slug}.svg`,
              altText: artwork.alt,
              width: 1000,
              height: 1000,
              position: 0,
              isPrimary: true,
            },
            {
              storeId: store.id,
              productId: product.id,
              type: 'IMAGE',
              url: `/demo/${artwork.slug}-detail.svg`,
              altText: `${artwork.alt} - detail view`,
              width: 1000,
              height: 1000,
              position: 1,
              isPrimary: false,
            },
          ],
        });
      }

      for (const gem of seed.gemstones ?? []) {
        const existing = await prisma.productGemstone.findFirst({
          where: { productId: product.id, stoneType: gem.stoneType },
        });
        if (!existing) {
          await prisma.productGemstone.create({
            data: {
              productId: product.id,
              stoneType: gem.stoneType,
              shape: gem.shape ?? null,
              count: gem.count,
              caratWeight: gem.caratWeight ?? null,
              clarityGrade: gem.clarityGrade ?? null,
              colourGrade: gem.colourGrade ?? null,
              certification: gem.certification ?? null,
            },
          });
        }
      }

      for (const [variantIndex, variantSeed] of seed.variants.entries()) {
        const sku = `${seed.sku}-${variantIndex + 1}`;
        const variant = await prisma.productVariant.upsert({
          where: { storeId_sku: { storeId: store.id, sku } },
          create: {
            storeId: store.id,
            productId: product.id,
            name: variantSeed.label,
            sku,
            ringSize: variantSeed.ringSize ?? null,
            lengthCm: variantSeed.lengthCm ?? null,
            colour: variantSeed.colour ?? null,
            metalPurity: seed.purity,
            grossWeightG: seed.grossWeightG,
            netWeightG: seed.netWeightG,
            price: seed.price,
            salePrice: seed.salePrice ?? null,
            costPrice: seed.costPrice,
            position: variantIndex,
            isDefault: variantIndex === 0,
          },
          update: {},
        });

        const item = await prisma.inventoryItem.upsert({
          where: { variantId_locationId: { variantId: variant.id, locationId: location.id } },
          create: {
            storeId: store.id,
            variantId: variant.id,
            locationId: location.id,
            onHand: variantSeed.stock,
            reorderPoint: 2,
            reorderQty: 5,
            avgUnitCost: seed.costPrice,
          },
          update: {},
        });

        const hasMovement = await prisma.inventoryMovement.findFirst({
          where: { inventoryItemId: item.id, type: 'INITIAL' },
        });
        if (!hasMovement && variantSeed.stock > 0) {
          await prisma.inventoryMovement.create({
            data: {
              storeId: store.id,
              inventoryItemId: item.id,
              locationId: location.id,
              type: 'INITIAL',
              quantityDelta: variantSeed.stock,
              balanceAfter: variantSeed.stock,
              unitCost: seed.costPrice,
              reason: 'Opening stock',
              actorType: 'SYSTEM',
            },
          });
        }
      }
    }

    // --- coupon ----------------------------------------------------------
    await prisma.coupon.upsert({
      where: { storeId_code: { storeId: store.id, code: 'WELCOME10' } },
      create: {
        storeId: store.id,
        code: 'WELCOME10',
        description: '10% off a first order',
        type: 'PERCENTAGE',
        value: '10.00',
        minSubtotal: '2000.00',
        maxDiscountAmount: '5000.00',
        usageLimit: 100,
        usageLimitPerCustomer: 1,
        firstOrderOnly: true,
        isActive: true,
      },
      update: {},
    });

    // --- shipping --------------------------------------------------------
    const zone = await prisma.shippingZone.upsert({
      where: { storeId_name: { storeId: store.id, name: `Inside ${storeSeed.city}` } },
      create: {
        storeId: store.id,
        name: `Inside ${storeSeed.city}`,
        countries: ['BD'],
        districts: [storeSeed.city],
        isDefault: true,
      },
      update: {},
    });
    const hasRate = await prisma.shippingRate.findFirst({ where: { zoneId: zone.id } });
    if (!hasRate) {
      await prisma.shippingRate.createMany({
        data: [
          {
            storeId: store.id,
            zoneId: zone.id,
            name: 'Standard (1-2 days)',
            type: 'FLAT',
            amount: '80.00',
            etaMinDays: 1,
            etaMaxDays: 2,
            freeAboveAmount: '10000.00',
          },
          {
            storeId: store.id,
            zoneId: zone.id,
            name: 'Express (same day)',
            type: 'FLAT',
            amount: '200.00',
            etaMinDays: 0,
            etaMaxDays: 1,
          },
        ],
      });
    }

    // --- payment methods -------------------------------------------------
    for (const [methodIndex, provider] of (['CASH_ON_DELIVERY', 'BKASH'] as const).entries()) {
      await prisma.storePaymentMethod.upsert({
        where: { storeId_provider: { storeId: store.id, provider } },
        create: {
          storeId: store.id,
          provider,
          label: provider === 'CASH_ON_DELIVERY' ? 'Cash on delivery' : 'bKash',
          isEnabled: provider === 'CASH_ON_DELIVERY',
          instructions:
            provider === 'CASH_ON_DELIVERY'
              ? 'Pay the courier when your order arrives.'
              : 'Send money to the number shown at checkout.',
          extraCharge: provider === 'CASH_ON_DELIVERY' ? '0.00' : '0.00',
          position: methodIndex,
          // No credentials: a provider stays unconfigured until the owner
          // enters their own, and nothing is faked on their behalf.
        },
        update: {},
      });
    }

    // --- customers and orders -------------------------------------------
    const customers = [];
    for (const customerSeed of CUSTOMERS.slice(0, index === 0 ? 5 : 3)) {
      const customer = await prisma.customer.upsert({
        where: { storeId_email: { storeId: store.id, email: customerSeed.email } },
        create: {
          storeId: store.id,
          email: customerSeed.email,
          phone: customerSeed.phone,
          firstName: customerSeed.firstName,
          lastName: customerSeed.lastName,
          passwordHash,
          emailVerifiedAt: now,
          status: 'ACTIVE',
          acceptsMarketing: true,
        },
        update: {},
      });
      customers.push(customer);

      const hasAddress = await prisma.customerAddress.findFirst({
        where: { customerId: customer.id },
      });
      if (!hasAddress) {
        await prisma.customerAddress.create({
          data: {
            storeId: store.id,
            customerId: customer.id,
            fullName: `${customerSeed.firstName} ${customerSeed.lastName}`,
            phone: customerSeed.phone,
            line1: 'House 12, Road 4',
            area: index === 0 ? 'Gulshan 1' : 'Khulshi',
            city: storeSeed.city,
            district: storeSeed.city,
            postalCode: index === 0 ? '1212' : '4000',
            isDefaultShipping: true,
            isDefaultBilling: true,
          },
        });
      }
    }

    const orderCount = await createDemoOrders(prisma, {
      storeId: store.id,
      storeName: storeSeed.name,
      city: storeSeed.city,
      customers,
    });

    console.warn(
      `  ${storeSeed.slug}: ${productCount} products, ${categoryNames.length} categories, ` +
        `${customers.length} customers, ${orderCount} orders`,
    );
  }

  console.warn(
    `\n  Demo sign-in — owners: ${STORES.map((s) => s.ownerEmail).join(', ')}` +
      `\n  Demo password: ${DEMO_PASSWORD}` +
      '\n  (local only; the seed refuses to run with NODE_ENV=production)',
  );
}

interface OrderContext {
  storeId: string;
  storeName: string;
  city: string;
  customers: Array<{
    id: string;
    email: string | null;
    phone: string | null;
    firstName: string | null;
    lastName: string | null;
  }>;
}

/**
 * A handful of orders spread over the last few weeks, in a mix of states, so
 * the dashboard and the reports have something real to show. Order totals are
 * computed from the line items rather than typed in, so they always reconcile.
 */
async function createDemoOrders(prisma: Prisma, ctx: OrderContext): Promise<number> {
  const existing = await prisma.order.count({ where: { storeId: ctx.storeId } });
  if (existing > 0) return existing;

  const variants = await prisma.productVariant.findMany({
    where: { storeId: ctx.storeId },
    include: { product: { select: { name: true, sku: true, costPrice: true } } },
    orderBy: { sku: 'asc' },
    take: 12,
  });
  if (variants.length === 0 || ctx.customers.length === 0) return 0;

  const store = await prisma.store.findUniqueOrThrow({ where: { id: ctx.storeId } });

  const plan: Array<{
    status: 'PENDING' | 'CONFIRMED' | 'PROCESSING' | 'SHIPPED' | 'DELIVERED' | 'CANCELLED';
    paymentStatus: 'UNPAID' | 'PAID';
    daysAgo: number;
    lines: number;
  }> = [
    { status: 'DELIVERED', paymentStatus: 'PAID', daysAgo: 28, lines: 2 },
    { status: 'DELIVERED', paymentStatus: 'PAID', daysAgo: 21, lines: 1 },
    { status: 'DELIVERED', paymentStatus: 'PAID', daysAgo: 14, lines: 1 },
    { status: 'SHIPPED', paymentStatus: 'PAID', daysAgo: 5, lines: 2 },
    { status: 'PROCESSING', paymentStatus: 'PAID', daysAgo: 3, lines: 1 },
    { status: 'CONFIRMED', paymentStatus: 'UNPAID', daysAgo: 2, lines: 1 },
    { status: 'PENDING', paymentStatus: 'UNPAID', daysAgo: 1, lines: 1 },
    { status: 'CANCELLED', paymentStatus: 'UNPAID', daysAgo: 9, lines: 1 },
  ];

  let sequence = store.orderSequence;
  let created = 0;

  for (const [orderIndex, spec] of plan.entries()) {
    const customer = ctx.customers[orderIndex % ctx.customers.length]!;
    const placedAt = new Date();
    placedAt.setDate(placedAt.getDate() - spec.daysAgo);

    const chosen = Array.from({ length: spec.lines }, (_, lineIndex) => {
      const variant = variants[(orderIndex + lineIndex) % variants.length]!;
      return { variant, quantity: 1 };
    });

    const lines = chosen.map(({ variant, quantity }) => {
      const unitPrice = money(variant.salePrice ?? variant.price);
      return {
        variant,
        quantity,
        unitPrice: toMoneyString(unitPrice),
        lineTotal: toMoneyString(unitPrice.times(quantity)),
      };
    });

    const subtotal = lines.reduce((acc, line) => acc.plus(money(line.lineTotal)), money(0));
    const shipping = money('80.00');
    const grandTotal = subtotal.plus(shipping);

    sequence += 1;
    const number = `${store.orderPrefix}-${sequence}`;

    const address = {
      fullName: `${customer.firstName ?? ''} ${customer.lastName ?? ''}`.trim(),
      phone: customer.phone ?? '',
      line1: 'House 12, Road 4',
      city: ctx.city,
      district: ctx.city,
      country: DEFAULTS.COUNTRY,
    };

    await prisma.order.create({
      data: {
        storeId: ctx.storeId,
        number,
        customerId: customer.id,
        email: customer.email,
        phone: customer.phone ?? '01800000000',
        status: spec.status,
        paymentStatus: spec.paymentStatus,
        fulfillmentStatus:
          spec.status === 'DELIVERED' || spec.status === 'SHIPPED' ? 'FULFILLED' : 'UNFULFILLED',
        subtotal: toMoneyString(subtotal),
        shippingTotal: toMoneyString(shipping),
        grandTotal: toMoneyString(grandTotal),
        amountPaid: spec.paymentStatus === 'PAID' ? toMoneyString(grandTotal) : '0.00',
        shippingAddress: address,
        billingAddress: address,
        shippingMethodLabel: 'Standard (1-2 days)',
        placedAt,
        createdAt: placedAt,
        confirmedAt: spec.status === 'PENDING' ? null : placedAt,
        shippedAt: spec.status === 'SHIPPED' || spec.status === 'DELIVERED' ? placedAt : null,
        deliveredAt: spec.status === 'DELIVERED' ? placedAt : null,
        cancelledAt: spec.status === 'CANCELLED' ? placedAt : null,
        cancelReason: spec.status === 'CANCELLED' ? 'Customer changed their mind' : null,
        source: 'STOREFRONT',
        items: {
          create: lines.map((line) => ({
            storeId: ctx.storeId,
            productId: line.variant.productId,
            variantId: line.variant.id,
            sku: line.variant.sku,
            name: line.variant.product.name,
            variantLabel: line.variant.name,
            quantity: line.quantity,
            unitPrice: line.unitPrice,
            costPrice: line.variant.costPrice ?? line.variant.product.costPrice,
            lineTotal: line.lineTotal,
            weightG: line.variant.grossWeightG,
            fulfilledQuantity:
              spec.status === 'DELIVERED' || spec.status === 'SHIPPED' ? line.quantity : 0,
            attributeSnapshot: {
              metalPurity: line.variant.metalPurity,
              netWeightG: line.variant.netWeightG?.toString() ?? null,
            },
          })),
        },
        statusHistory: {
          create: {
            storeId: ctx.storeId,
            toStatus: spec.status,
            note: 'Seeded demo order',
            actorType: 'SYSTEM',
            createdAt: placedAt,
          },
        },
      },
    });
    created += 1;
  }

  await prisma.store.update({
    where: { id: ctx.storeId },
    data: { orderSequence: sequence },
  });

  return created;
}

function slugify(value: string): string {
  return value
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9\s-]/g, '')
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-');
}
