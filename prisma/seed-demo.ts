interface ProductSeed {
  name: string;
  sku: string;
  category: string;
  jewelleryType:
    'RING' | 'NECKLACE' | 'EARRING' | 'BRACELET' | 'BANGLE' | 'PENDANT' | 'CHAIN' | 'SET';
  metalType: 'GOLD' | 'SILVER' | 'ROSE_GOLD' | 'WHITE_GOLD' | 'GOLD_PLATED' | 'NONE';
  purity: string | null;
  /** Metal weight in grams; drives rate-based pricing. */
  netWeightG: string | null;
  grossWeightG: string | null;
  price: string;
  costPrice: string;
  salePrice?: string;
  makingCharge?: string;
  makingChargeType?: 'FLAT' | 'PER_GRAM' | 'PERCENT';
  wastagePercent?: string;
  rateBased?: boolean;
  hallmarked?: boolean;
  stoneType?: string;
  shortDescription: string;
  variants: Array<{
    label: string;
    ringSize?: string;
    lengthCm?: string;
    colour?: string;
    stock: number;
  }>;
  gemstones?: Array<{
    stoneType: string;
    shape?: string;
    count: number;
    caratWeight?: string;
    clarityGrade?: string;
    colourGrade?: string;
    certification?: string;
  }>;
  featured?: boolean;
}

